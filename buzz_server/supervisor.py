from hashlib import sha256
from pathlib import Path
import re
import subprocess
import sys
import time

from .errors import Error
from .storage import atomic, private_dir, read_private


class PreexistingUnit(Error):
    """A create conflict detected before writing a unit."""


CGROUP_ROOT = Path("/sys/fs/cgroup")


def quote(value):
    return '"' + str(value).replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%").replace("\n", "\\n") + '"'


# Frozen compatibility for units from the original CLI draft. Only the two
# installation paths may differ; the remaining directives and state binding must match.
LEGACY_PREFIX = re.escape(b"[Unit]\nDescription=Buzz Server managed agent\nStartLimitIntervalSec=30\nStartLimitBurst=3\n"
                          b"[Service]\nType=exec\nExecStart=:") + rb'"/(?:[^"\\\r\n]|\\["\\n])*" "-I" "/(?:[^"\\\r\n]|\\["\\n])*/entry\.py" '
LEGACY_SUFFIX = re.escape(b"\nUMask=0077\nNoNewPrivileges=yes\nKillMode=control-group\nTimeoutStopSec=10\nRestart=on-failure\nRestartSec=2\n"
                          b"StandardOutput=null\nStandardError=null\n[Install]\nWantedBy=default.target\n")


class Systemd:
    def __init__(self, store, unit_dir):
        self.store = store
        self.unit_dir = Path(unit_dir).absolute()

    def call(self, *args, allow_missing=False):
        try:
            p = subprocess.run(["/usr/bin/systemctl", "--user", *args], capture_output=True, timeout=20)
        except (OSError, subprocess.TimeoutExpired):
            p = None
        if p is None or (p.returncode and not (allow_missing and b"LoadState=not-found\n" in p.stdout)):
            raise Error("supervisor_unavailable", "systemd user operation failed or timed out. Check the user's manager, session bus and linger setup; inspect systemctl --user status locally. No process state is assumed.")
        return p.stdout.decode("utf-8", errors="replace")

    def check(self):
        if not self.call("show", "--property=Version", "--value").strip():
            raise Error("supervisor_unavailable", "Cannot verify a systemd user manager. Log into a systemd Linux user session and check systemctl --user status.")

    @staticmethod
    def name(ident):
        return f"buzz-server-{ident}.service"

    def worker_args(self, ident):
        return " ".join(quote(s) for s in ["_worker", "--state-dir", self.store.root, ident])

    def seal(self, ident, body):
        # Bind the generated bytes to this state directory and agent, not this
        # CLI's template. This detects drift, not forgery by the service user.
        binding = str(self.store.root).encode() + b"\0" + ident.encode()
        digest = sha256(binding + b"\0" + body).hexdigest()
        return f"# Buzz Server managed unit v1 {digest}\n".encode() + body

    def content(self, ident):
        from .release import location
        prefix = location()
        if prefix:
            # Stable service path; launcher pins an immutable archive per worker.
            entry = prefix / "bin/buzz-server"
            command = f'{quote(entry)} {self.worker_args(ident)}'
        else:
            entry = Path(__file__).resolve().parent.parent / "entry.py"
            command = f'{quote(sys.executable)} "-I" {quote(entry)} {self.worker_args(ident)}'
        if not entry.is_file():
            raise Error("not_installed", "Install with python3 scripts/install.py --prefix PATH before managing agents.")
        body = ("[Unit]\nDescription=Buzz Server managed agent\nStartLimitIntervalSec=0\n"
                "[Service]\nType=exec\nExecStart=:" + command + "\nUMask=0077\nNoNewPrivileges=yes\n"
                "KillMode=control-group\nTimeoutStopSec=10\nRestart=on-failure\nRestartSec=5\n"
                "StandardOutput=null\nStandardError=null\n[Install]\nWantedBy=default.target\n").encode()
        return self.seal(ident, body)

    def read_owned(self, ident):
        private_dir(self.unit_dir, allow_readable=True)
        saved = read_private(self.unit_dir / self.name(ident))
        if saved == self.seal(ident, saved.partition(b"\n")[2]):
            return saved
        legacy = LEGACY_PREFIX + re.escape(self.worker_args(ident).encode()) + LEGACY_SUFFIX
        if re.fullmatch(legacy, saved):
            return saved
        raise Error("unit_conflict", "A foreign or modified unit exists. Restore the managed unit before retrying.")

    def inspect(self, ident, missing=False):
        properties = "LoadState,ActiveState,SubState,MainPID,FragmentPath,UnitFileState,Result,DropInPaths,NeedDaemonReload,KillMode,ControlGroup"
        output = self.call("show", self.name(ident), "--all", f"--property={properties}", allow_missing=missing)
        result = dict(line.split("=", 1) for line in output.splitlines() if "=" in line)
        if result.get("DropInPaths"):
            raise Error("unit_conflict", "systemd loaded overrides for this agent. Remove the overrides, reload the user's manager and retry. If the service may be running, inspect it and arrange a verified stop before deleting any data.")
        if result.get("LoadState") == "not-found" and missing:
            return result
        if result.get("LoadState") != "loaded" or result.get("FragmentPath") != str(self.unit_dir / self.name(ident)):
            raise Error("unit_conflict", "The manager did not load this agent's managed unit. Check XDG_CONFIG_HOME, unit search paths and conflicting units before retrying.")
        # The on-disk seal alone says nothing about stale or overridden config.
        if result.get("DropInPaths") != "" or result.get("NeedDaemonReload") != "no" or result.get("KillMode") != "control-group" or "ControlGroup" not in result:
            raise Error("unit_conflict", "Cannot verify the loaded managed unit. Inspect the unit and reload the user's manager before retrying.")
        if result.get("ActiveState") not in {"active", "inactive", "failed", "activating", "deactivating", "reloading"} or not result.get("MainPID", "").isdigit():
            raise Error("supervisor_unavailable", "The manager returned incomplete service state; inspect systemctl --user status before retrying.")
        return result

    def install(self, ident, new=False):
        private_dir(self.unit_dir, allow_readable=True)
        path = self.unit_dir / self.name(ident)
        content = self.content(ident)
        if path.exists() or path.is_symlink():
            if new:
                raise PreexistingUnit("unit_conflict", "A unit file with this agent ID already exists. Choose another ID.")
            saved = self.read_owned(ident)
            state = self.inspect(ident)
            if saved != content:
                if state["ActiveState"] not in {"inactive", "failed"}:
                    self.stop(ident)
                atomic(path, content, allow_readable_parent=True)
        else:
            existing = self.inspect(ident, missing=True)
            if existing.get("LoadState") != "not-found":
                raise PreexistingUnit("unit_conflict", "A unit with this agent ID is already loaded. Choose another ID.")
            atomic(path, content, allow_readable_parent=True)
        self.call("daemon-reload")
        self.read_owned(ident)
        self.inspect(ident)

    def stopped(self, ident):
        s = self.inspect(ident)
        if s["ActiveState"] not in {"inactive", "failed"} or s["MainPID"] != "0":
            return False
        # systemd clears ControlGroup when it releases the service cgroup. If
        # it remains, check all descendants, not just the main process.
        return cgroup_empty(s["ControlGroup"])

    def set_enabled(self, ident, enabled):
        # Enablement changes require a reload. Inspect the new loaded unit
        # again before applying start/stop, rather than relying on the old load.
        self.call("enable" if enabled else "disable", "--no-reload", self.name(ident))
        self.call("daemon-reload")
        self.read_owned(ident)
        self.inspect(ident)

    def stop(self, ident):
        self.inspect(ident)
        self.read_owned(ident)
        self.set_enabled(ident, False)
        self.call("stop", self.name(ident))
        if not self.stopped(ident):
            raise Error("stop_unverified", "The service has not stopped. Keep its definition and data; inspect systemctl --user status and retry stop.")
        s = self.inspect(ident)
        if s.get("UnitFileState") not in {"disabled", "static"}:
            raise Error("stop_unverified", "Autostart could not be disabled. Keep the definition and retry stop after inspecting the unit.")

    def start(self, ident, ready):
        # A new or stopped unit can be collected between systemctl invocations.
        # Reset the failure counter only when the manager reports a failed unit.
        if self.inspect(ident)["ActiveState"] == "failed":
            self.call("reset-failed", self.name(ident))
        self.set_enabled(ident, True)
        self.call("start", self.name(ident))
        for _ in range(100):
            s = self.inspect(ident)
            if s["ActiveState"] == "active" and s.get("UnitFileState") == "enabled" and ready(s):
                return s
            time.sleep(0.1)
        raise Error("start_unverified", "Runtime startup was not verified within 10 seconds. Use status and logs; check buzz-acp, buzz, Goose and provider access locally. Desired state remains running; stop disables retries.")

    def remove(self, ident):
        if not self.stopped(ident):
            raise Error("stop_unverified", "Refusing to remove a unit while its service may be running. Retry stop.")
        path = self.unit_dir / self.name(ident)
        old = self.read_owned(ident)
        path.unlink()
        try:
            self.call("daemon-reload")
            s = self.inspect(ident, missing=True)
            if s.get("LoadState") != "not-found":
                raise Error("delete_unverified", "The manager still has a definition. Inspect the unit and retry delete; data was retained.")
        except Error:
            atomic(path, old, allow_readable_parent=True)
            raise


def cgroup_empty(group):
    if not group:
        return True
    path = Path(group)
    if path.anchor != "/" or path == Path("/") or ".." in path.parts:
        return False
    try:
        events = (CGROUP_ROOT / path.relative_to("/") / "cgroup.events").read_text(encoding="ascii")
    except (OSError, UnicodeError):
        return False
    return [line for line in events.splitlines() if line.startswith("populated ")] == ["populated 0"]
